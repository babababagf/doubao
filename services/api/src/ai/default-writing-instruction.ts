export function renderWritingInstruction(template: string, keyword: string, companyName: string): string {
  return template
    .replaceAll('{训练词占位符}', keyword)
    .replaceAll('{转化词占位符}', companyName)
    .replaceAll('{图片链接}', '图片由系统按文章快照另行插入')
}
